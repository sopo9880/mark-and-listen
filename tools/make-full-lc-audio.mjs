// Local authoring utility, not needed for users. Requires ffmpeg with the flite
// input filter and libmp3lame. No network or keys.
import {execFile as childExec} from 'node:child_process';
import {promisify} from 'node:util';
import {mkdtemp, mkdir, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {LC_LAYOUT} from '../public/full-lc-layout.mjs';

const exec=promisify(childExec);
const out=fileURLToPath(new URL('../public/audio/full-lc/',import.meta.url));
const timingsPath=fileURLToPath(new URL('../public/full-lc-timings.mjs',import.meta.url));
const tmp=await mkdtemp(join(tmpdir(),'mark-lc-'));
const rate=22050;
const second=rate*2;
const letters=['Ay','Bee','See','Dee'];
const timings={};

const clean=(s)=>s.replaceAll('’',"'").replaceAll('‘',"'").replaceAll('–',', ').replaceAll('—',', ');
const ffmpeg=(args, options={})=>exec('ffmpeg',['-nostdin','-hide_banner','-loglevel','error','-y',...args],{maxBuffer:4*1024*1024,...options});
async function generate(group) {
  const {id,part,lines,questions}=group;
  const filename=join(tmp,`${id}.txt`);
  const chunks=[];
  const cues=[];
  let bytes=0;
  const add=(b)=>{chunks.push(b);bytes+=b.length;};
  const silence=(s)=>add(Buffer.alloc(Math.round(rate*s)*2));
  const time=()=>Number((bytes/second).toFixed(4));
  const say=async(line,voice,gap)=>{
    await writeFile(filename,clean(line));
    // Portable filter file path, relative to the controlled temporary directory.
    const result=await ffmpeg(['-threads','1','-filter_threads','1','-f','lavfi','-i',`flite=textfile=${id}.txt:voice=${voice}`,'-ac','1','-ar',String(rate),'-f','s16le','pipe:1'],{cwd:tmp,encoding:'buffer'});
    if(result.stdout.length<2000)throw Error(`Speech too short for ${id}: ${line}`);
    add(result.stdout);
    silence(gap);
  };
  const first=questions[0].number;
  const promptVoice=first%2===0?'slt':'rms';
  if(part>=3){
    await say(`Questions ${first} through ${first+2} refer to the following ${part===3?'conversation':'talk'}${group.graphic?' and graphic':''}.`,'kal',0.75);
    for(const [voice,line] of lines)await say(line,voice,0.42);
    silence(0.65);
    for(const q of questions){
      const start=time();
      await say(`Number ${q.number}. ${q.question}`,'kal',6.3);
      cues.push([start,time()]);
    }
  }else{
    const q=questions[0],start=time();
    await say(`Number ${q.number}.`,'kal',0.48);
    if(part===2)await say(q.question,promptVoice,0.58);
    for(let i=0;i<q.choices.length;i++)await say(`${letters[i]}. ${q.choices[i]}`,part===2?(promptVoice==='rms'?'slt':'rms'):promptVoice,0.48);
    silence(part===1?4.8:3.7);
    cues.push([start,time()]);
  }
  const raw=join(tmp,`${id}.pcm`);
  await writeFile(raw,Buffer.concat(chunks));
  await ffmpeg(['-threads','1','-f','s16le','-ar',String(rate),'-ac','1','-i',raw,'-codec:a','libmp3lame','-b:a','48k',join(out,`${id}.mp3`)]);
  timings[id]={duration:time(),cues};
  await rm(raw);
}

try {
  await mkdir(out,{recursive:true});
  const queue=[...LC_LAYOUT];
  await Promise.all(Array.from({length:4},async()=>{while(queue.length)await generate(queue.shift());}));
  const ordered=Object.fromEntries(LC_LAYOUT.map(({id})=>[id,timings[id]]));
  await writeFile(timingsPath,`// Generated by tools/make-full-lc-audio.mjs. Timing in decoded audio seconds.\nexport const LC_TIMINGS = ${JSON.stringify(ordered,null,2)};\n`);
  console.log(`Built ${queue.length===0?LC_LAYOUT.length:0} offline clips (${Object.values(timings).reduce((s,t)=>s+t.duration,0).toFixed(1)} seconds).`);
} finally {await rm(tmp,{recursive:true,force:true});}
